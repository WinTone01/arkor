//! vkBasalt (Vulkan post-processing layer): per-game effects rendered to a `vkBasalt.conf`.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};

/// Built-in vkBasalt effects.
pub const BUILTIN: [&str; 5] = ["cas", "dls", "fxaa", "smaa", "lut"];

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct VkBasalt {
    pub enabled: bool,
    /// Effects in the order they run: built-in names or ReShade `.fx` file paths.
    pub effects: Vec<String>,
    /// CAS sharpness 0-100.
    pub cas_sharpness: u32,
    /// DLS sharpness / denoise 0-100.
    pub dls_sharpness: u32,
    pub dls_denoise: u32,
    pub lut_file: Option<PathBuf>,
    pub toggle_key: String,
    /// ReShade shader folders (Shaders/, Textures/) for `.fx` effects.
    pub reshade_shaders: Option<PathBuf>,
}

impl Default for VkBasalt {
    fn default() -> Self {
        Self {
            enabled: false,
            effects: vec!["cas".into()],
            cas_sharpness: 40,
            dls_sharpness: 50,
            dls_denoise: 17,
            lut_file: None,
            toggle_key: "Home".into(),
            reshade_shaders: None,
        }
    }
}

fn effect_name(e: &str) -> String {
    if BUILTIN.contains(&e) {
        return e.to_string();
    }
    // ReShade effects are named after their file ("Daltonize.fx" -> "daltonize").
    std::path::Path::new(e)
        .file_stem()
        .map(|s| s.to_string_lossy().to_lowercase())
        .unwrap_or_default()
}

impl VkBasalt {
    pub fn toggle_effect(&mut self, effect: &str) {
        if let Some(i) = self.effects.iter().position(|e| e == effect) {
            self.effects.remove(i);
        } else {
            self.effects.push(effect.to_string());
        }
    }

    pub fn render(&self) -> String {
        let usable: Vec<&String> = self
            .effects
            .iter()
            .filter(|e| e.as_str() != "lut" || self.lut_file.is_some())
            .collect();
        let mut out = String::from("# Generated by Arkor. Change it from Arkor.\n");
        out.push_str(&format!(
            "effects = {}\n",
            usable
                .iter()
                .map(|e| effect_name(e))
                .collect::<Vec<_>>()
                .join(":")
        ));
        out.push_str(&format!(
            "casSharpness = {:.2}\n",
            self.cas_sharpness as f32 / 100.0
        ));
        out.push_str(&format!(
            "dlsSharpness = {:.2}\n",
            self.dls_sharpness as f32 / 100.0
        ));
        out.push_str(&format!(
            "dlsDenoise = {:.2}\n",
            self.dls_denoise as f32 / 100.0
        ));
        if let Some(lut) = &self.lut_file {
            out.push_str(&format!("lutFile = {}\n", lut.display()));
        }
        if !self.toggle_key.is_empty() {
            out.push_str(&format!("toggleKey = {}\n", self.toggle_key));
        }
        if let Some(dir) = &self.reshade_shaders {
            out.push_str(&format!(
                "reshadeTexturePath = {}\n",
                dir.join("Textures").display()
            ));
            out.push_str(&format!(
                "reshadeIncludePath = {}\n",
                dir.join("Shaders").display()
            ));
        }
        for e in usable.iter().filter(|e| !BUILTIN.contains(&e.as_str())) {
            out.push_str(&format!("{} = {e}\n", effect_name(e)));
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_builtin_and_reshade_effects() {
        let mut v = VkBasalt {
            reshade_shaders: Some("/sh".into()),
            ..Default::default()
        };
        v.toggle_effect("smaa");
        v.toggle_effect("/sh/Shaders/Daltonize.fx");
        v.toggle_effect("lut"); // no lut file: skipped
        let text = v.render();
        assert!(text.contains("effects = cas:smaa:daltonize\n"), "{text}");
        assert!(text.contains("casSharpness = 0.40\n"));
        assert!(text.contains("daltonize = /sh/Shaders/Daltonize.fx\n"));
        assert!(text.contains("reshadeIncludePath = /sh/Shaders\n"));
        v.toggle_effect("cas");
        assert!(v.render().contains("effects = smaa:daltonize\n"));
    }
}
